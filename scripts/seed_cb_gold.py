    con = sqlite3.connect(DB)
    inserted = 0
    for d, country, total, chg in DATA:
        con.execute(
            "INSERT OR REPLACE INTO cb_gold (country, date, total_tonnes, monthly_chg_tonnes) "
            "VALUES (?, ?, ?, ?)",
            (country, d, total, chg),
        )
        inserted += 1
    con.commit()
    con.close()
